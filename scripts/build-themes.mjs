#!/usr/bin/env node
/**
 * 主题构建脚本
 *
 * 扫描 src/themes/<key>/theme.json，按环境变量 THEME_SLOTS 决定把哪些主题打进产物：
 *   THEME_SLOTS=v1        → 只打包模板一
 *   THEME_SLOTS=v1,v2     → 两套都打包
 *   未设置                → 打包全部已安装主题
 *
 * 产物：
 *   src/themes/generated.ts            静态 import 注册表（Next 只会打包这里列出的主题）
 *   public/themes/<key>/theme.css      主题样式
 *   public/themes/<key>/theme.json     主题清单
 *   public/themes/manifest.json        后台外观页读取的已构建主题列表
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = process.cwd();
const themesDir = join(root, "src/themes");
const publicThemes = join(root, "public/themes");

function readJson(file) {
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (e) {
    throw new Error(`${file} 不是合法 JSON：${e.message}`);
  }
}

function pascal(key) {
  return key.replace(/[^a-zA-Z0-9]+/g, "_").replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
}

function scanThemes() {
  if (!existsSync(themesDir)) return [];
  return readdirSync(themesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => {
      const dir = join(themesDir, d.name);
      const manifestPath = join(dir, "theme.json");
      if (!existsSync(manifestPath)) return null;
      const manifest = readJson(manifestPath);
      const id = String(manifest.id || d.name).trim().toLowerCase();
      if (!/^[a-z0-9][a-z0-9_-]*$/.test(id)) {
        throw new Error(`主题 ${d.name} 的 id 不合法：${id}`);
      }
      for (const required of ["Layout.tsx", "Home.tsx"]) {
        if (!existsSync(join(dir, required))) {
          throw new Error(`主题 ${id} 缺少 ${required}`);
        }
      }
      return {
        key: id,
        dir,
        name: String(manifest.name || id),
        desc: String(manifest.description || manifest.desc || ""),
        version: String(manifest.version || "1.0.0"),
        swatch: Array.isArray(manifest.swatch) ? manifest.swatch.slice(0, 4).map(String) : [],
        css: String(manifest.css || ""),
      };
    })
    .filter(Boolean)
    .sort((a, b) => a.key.localeCompare(b.key));
}

function parseSlots() {
  const raw = String(process.env.THEME_SLOTS ?? "").trim();
  if (!raw) return null;
  const keys = raw
    .split(",")
    .map((v) => v.trim().toLowerCase())
    .filter(Boolean);
  return keys.length ? [...new Set(keys)] : null;
}

function generate(selected) {
  const imports = [];
  const items = [];
  for (const t of selected) {
    const name = pascal(t.key);
    imports.push(`import Layout${name} from "./${t.key}/Layout";`);
    imports.push(`import Home${name} from "./${t.key}/Home";`);
    items.push(`  {
    key: ${JSON.stringify(t.key)},
    name: ${JSON.stringify(t.name)},
    desc: ${JSON.stringify(t.desc)},
    version: ${JSON.stringify(t.version)},
    swatch: ${JSON.stringify(t.swatch)},
    css: ${JSON.stringify(t.css ? `/themes/${t.key}/theme.css` : "")},
    Layout: Layout${name},
    Home: Home${name},
  },`);
  }

  const content = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-themes.mjs — 请勿手动编辑。
// 修改主题包后运行 \`npm run themes\` 重新生成；可用主题由环境变量 THEME_SLOTS 决定。
import type { ComponentType, ReactNode } from "react";
${imports.join("\n")}

export interface GeneratedTheme {
  key: string;
  name: string;
  desc: string;
  version: string;
  swatch: string[];
  css: string;
  Layout: ComponentType<{ children: ReactNode }>;
  Home: ComponentType;
}

export const THEMES: GeneratedTheme[] = [
${items.join("\n")}
];
`;

  writeFileSync(join(themesDir, "generated.ts"), content, "utf8");
}

function publish(selected) {
  rmSync(publicThemes, { recursive: true, force: true });
  mkdirSync(publicThemes, { recursive: true });
  for (const t of selected) {
    const out = join(publicThemes, t.key);
    mkdirSync(out, { recursive: true });
    if (t.css && existsSync(join(t.dir, t.css))) {
      cpSync(join(t.dir, t.css), join(out, "theme.css"));
    }
    writeFileSync(
      join(out, "theme.json"),
      JSON.stringify(
        { id: t.key, name: t.name, description: t.desc, version: t.version, swatch: t.swatch },
        null,
        2,
      ),
      "utf8",
    );
  }
  writeFileSync(
    join(publicThemes, "manifest.json"),
    JSON.stringify(
      selected.map((t) => ({
        key: t.key,
        name: t.name,
        desc: t.desc,
        version: t.version,
        swatch: t.swatch,
        css: t.css ? `/themes/${t.key}/theme.css` : "",
      })),
      null,
      2,
    ),
    "utf8",
  );
}

function main() {
  const installed = scanThemes();
  if (!installed.length) throw new Error("src/themes 下没有找到任何主题包");

  const slots = parseSlots();
  let selected = installed;
  if (slots) {
    const known = new Set(installed.map((t) => t.key));
    const missing = slots.filter((k) => !known.has(k));
    if (missing.length) console.warn(`[themes] THEME_SLOTS 中的主题未安装：${missing.join(", ")}`);
    selected = installed.filter((t) => slots.includes(t.key));
    if (!selected.length) {
      throw new Error(`THEME_SLOTS=${slots.join(",")} 没有匹配到已安装主题（已安装：${installed.map((t) => t.key).join(", ")}）`);
    }
  }

  generate(selected);
  publish(selected);

  const skipped = installed.filter((t) => !selected.includes(t));
  console.log(`[themes] 已构建：${selected.map((t) => `${t.key}(${t.name})`).join("、")}`);
  if (skipped.length) console.log(`[themes] 已跳过：${skipped.map((t) => t.key).join("、")}`);
}

try {
  main();
} catch (e) {
  console.error(`[themes] ${e instanceof Error ? e.message : e}`);
  process.exit(1);
}

export {};
